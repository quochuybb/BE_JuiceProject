const { DataTypes } = require('sequelize');
const { sequelize } = require('../config/database');

const User = sequelize.define('User', {
  id: {
    type: DataTypes.INTEGER,
    primaryKey: true,
    autoIncrement: true
  },
  username: {
    type: DataTypes.STRING(50),
    allowNull: false,
    unique: true
  },
  password_hash: {
    type: DataTypes.STRING(255),
    allowNull: false
  },
  gold: {
    type: DataTypes.INTEGER,
    defaultValue: 0
  },
  gem: {
    type: DataTypes.INTEGER,
    defaultValue: 0
  },
  mmr: {
    type: DataTypes.INTEGER,
    defaultValue: 1000
  },
  session_data: {
    type: DataTypes.TEXT,
    allowNull: true
  }
}, {
  tableName: 'users',
  timestamps: true,
  createdAt: 'created_at',
  updatedAt: false
});

module.exports = User;
